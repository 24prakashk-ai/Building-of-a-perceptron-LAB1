## Perceptron Algorithm for robot inverse kinematics prediction
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.linear_model import Perceptron
from sklearn.multioutput import MultiOutputClassifier
from sklearn.metrics import accuracy_score, confusion_matrix

# Load data
data = pd.read_csv("robot_inverse_kinematics_dataset.csv")

# Features: joint angles q1-q6
x = data[['q1', 'q2', 'q3', 'q4', 'q5', 'q6']]

# Perceptron needs class labels, so bin each continuous output into 3 classes
y_x = pd.cut(data['x'], bins=3, labels=['low', 'mid', 'high'])
y_y = pd.cut(data['y'], bins=3, labels=['low', 'mid', 'high'])
y_z = pd.cut(data['z'], bins=3, labels=['low', 'mid', 'high'])

# Combine all three into one target dataframe
y = pd.DataFrame({'x_class': y_x, 'y_class': y_y, 'z_class': y_z})

# Train test split
x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.4, random_state=42)

# creating a perceptron wrapped for multi-output prediction
base_perceptron = Perceptron(max_iter=100, random_state=42)
perceptron = MultiOutputClassifier(base_perceptron)
perceptron.fit(x_train, y_train)

# Predict the test data (returns 3 columns: x_class, y_class, z_class)
y_pred = perceptron.predict(x_test)
y_pred_df = pd.DataFrame(y_pred, columns=['x_class', 'y_class', 'z_class'])

# accuracy score for each output separately
for i, col in enumerate(['x_class', 'y_class', 'z_class']):
    acc = accuracy_score(y_test[col], y_pred_df[col])
    print(f"Accuracy for {col}:", acc)

# confusion matrix for each output separately
for i, col in enumerate(['x_class', 'y_class', 'z_class']):
    cf = confusion_matrix(y_test[col], y_pred_df[col])
    print(f"Confusion Matrix for {col}:\n", cf)

# Display the learned weights and bias for each output's underlying model
for i, col in enumerate(['x_class', 'y_class', 'z_class']):
    weights = perceptron.estimators_[i].coef_
    bias = perceptron.estimators_[i].intercept_
    print(f"Learned Weights for {col}:", weights)
    print(f"Learned Bias for {col}:", bias)

